import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { loadProjectTs } from './lib/load-project-ts.mjs';
const path='src/data/season-recap-corrections-2026.json';
const stored=JSON.parse(await readFile(path,'utf8'));
const audit=JSON.parse(await readFile('src/data/season-no-hitters-2026.json','utf8'));
const records=JSON.parse(await readFile('data/season-reviews/2026-canonical.json','utf8'));
const event=audit.combined.find(r=>r.gamePk===822899);
assert(event,'Verified combined game required');assert(!stored[event.startId],'One-time regeneration already recorded; refusing to regenerate');
const record=records.find(r=>r.id===event.startId);
const response=await fetch(`https://www.toetheslab.com/api/starts/${record.id}`);
assert.equal(response.status,200);const detail=await response.json();
assert.equal(detail.gamePk,event.gamePk);assert.deepEqual(detail.line,record.line);assert.equal(detail.gameScorePlus,record.gameScorePlus);
const {canonicalRecordToFormStart}=loadProjectTs('src/lib/canonical-start-summary.ts');
const {withSeasonNoHitterNotable}=loadProjectTs('src/lib/season-no-hitters.ts');
const {generateStartRecap}=loadProjectTs('src/lib/start-recap-copy.ts');
const input=withSeasonNoHitterNotable({...canonicalRecordToFormStart(record,0),gameScorePlusBreakdown:detail.gameScorePlusBreakdown,pitchEvents:detail.pitchEvents??[],arsenalEventSummary:detail.arsenalEventSummary});
const summary=generateStartRecap(input);
assert(summary.includes('combined no-hitter'));assert(summary.includes('6.0 hitless innings'));assert(!summary.includes('individual no-hitter'));
stored[record.id]={summary,generatedAt:new Date().toISOString(),generator:'generateStartRecap: extracted existing deterministic recap harness',generationCount:1,inputSha256:createHash('sha256').update(JSON.stringify(input)).digest('hex'),gamePk:event.gamePk,source:event.source};
await writeFile(path,JSON.stringify(stored,null,2)+'\n');
await writeFile('outputs/off2/recap-regeneration.json',JSON.stringify({input,receipt:stored[record.id]},null,2)+'\n');
console.log(JSON.stringify(stored[record.id],null,2));
